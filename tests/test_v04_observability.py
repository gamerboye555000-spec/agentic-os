# E24-E26 — the operator surface
#
# Exactly FOUR cases below invoke the CLI as a subprocess, one per leaf. Every
# other case here runs in-process: the projection is a pure function over rows,
# so a subprocess-per-case module would buy nothing and cost half the suite's
# remaining CI margin (§18.4).

def _run_cli(root: Path, *argv) -> subprocess.CompletedProcess:
    env = os.environ.copy()
    env.pop("PYTHONPATH", None)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    return subprocess.run(
        [sys.executable, str(REPO_ROOT / "aos.py"), "--root", str(root), *argv],
        cwd=str(REPO_ROOT), env=env, capture_output=True, text=True,
        timeout=120,
    )


