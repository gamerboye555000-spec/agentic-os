def _code_only(source: str) -> str:
    """A module's EXECUTABLE source: comments and docstrings removed.

    Every scan in this file that forbids a token is about code, not prose: a
    comment or docstring that names a forbidden thing IN ORDER TO FORBID IT is
    the documentation, not the defect (the `_executable` idiom already used by
    `test_v04_workflow_recovery`).
    """
    import ast

    tree = ast.parse(source)
    for node in ast.walk(tree):
        if not isinstance(
            node, (ast.Module, ast.ClassDef, ast.FunctionDef,
                   ast.AsyncFunctionDef)
        ):
            continue
        body = list(node.body)
        if (
            body
            and isinstance(body[0], ast.Expr)
            and isinstance(body[0].value, ast.Constant)
            and isinstance(body[0].value.value, str)
        ):
            node.body = body[1:] or [ast.Pass()]
    return ast.unparse(tree)


