def clone(led: Ledger) -> Ledger:
    """A private, WRITABLE copy of a shared scenario, for the cases that plant
    damage. The shared original is never mutated."""
    fresh = object.__new__(Ledger)
    fresh.actor = led.actor
    fresh.artifact = led.artifact
    fresh.report = led.report
    fresh.seed = led.seed
    fresh.workflow_id = led.workflow_id
    fresh.conn = db.connect(":memory:")
    led.conn.backup(fresh.conn)
    return fresh


class ObservabilityCase(unittest.TestCase):
    maxDiff = None

    def attributes(self, holder) -> dict:
        return dict(holder.attributes)

    def span_of(self, projection, kind, **match):
        for span in projection.spans:
            if span.kind != kind:
                continue
            attributes = dict(span.attributes)
            if all(attributes.get(k) == v for k, v in match.items()):
                return span
        raise AssertionError(f"no {kind} span matching {match}")

    def log_of(self, projection, event):
        for record in projection.logs:
            if record.event_name == f"aos.workflow.{event}":
                return record
        raise AssertionError(f"no log record for {event}")


