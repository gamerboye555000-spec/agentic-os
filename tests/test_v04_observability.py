class Ledger:
    """A real store on an in-memory ledger, driven through `submit` only.

    Deliberately independent of any `TestCase`: the scenarios below are built
    once and shared read-only, which is what keeps this module inside its 60 s
    budget without a single duplicated fixture build.
    """

    def __init__(self, artifact=None, report=None, actor="human"):
        self.actor = actor
        self.artifact = artifact if artifact is not None else work_spec()
        self.report = report if report is not None else compile_report(
            self.artifact
        )
        self.seed = 200
        self.conn = db.connect(":memory:")
        self.conn.executescript(db.SCHEMA_SQL)
        self.conn.execute(
            "INSERT OR REPLACE INTO meta (key, value) VALUES "
            "('schema_version', ?)", (db.SCHEMA_VERSION,)
        )
        self.conn.execute(
            "INSERT INTO tasks (id, project_id, title, kind, status, "
            "priority, created_at, updated_at) VALUES "
            "(7, NULL, 't', 'code', 'ready', 2, ?, ?)", (NOW, NOW)
        )
        self.conn.commit()
        outcome = self.submit("admit_work_spec", {
            "work_spec_document": self.artifact,
            "report_document": self.report,
        }, workflow_id=None, expected_revision=0)
        assert outcome.status == "accepted", outcome.reason
        self.workflow_id = outcome.workflow_id

    def submit(self, verb, payload=None, workflow_id=..., expected_revision=None,
               seed=None, created_at=NOW):
        if seed is None:
            self.seed += 1
            seed = self.seed
        if workflow_id is ...:
            workflow_id = self.workflow_id
        if expected_revision is None:
            record = workflow_store.read_workflow(self.conn, workflow_id)
            expected_revision = record.revision if record else 0
        return workflow_store.submit(self.conn, command(
            verb, workflow_id, expected_revision, payload, seed=seed,
            created_at=created_at, actor=self.actor,
        ))

    def ok(self, verb, payload=None, **kwargs):
        outcome = self.submit(verb, payload, **kwargs)
        assert outcome.status == "accepted", f"{verb}: {outcome.reason}"
        return outcome

    @property
    def record(self):
        return workflow_store.read_workflow(self.conn, self.workflow_id)

    @property
    def state(self):
        return self.record.state

    def outstanding(self):
        views = workflow_store.list_outstanding_intents(
            self.conn, workflow_id=self.workflow_id
        )
        assert views, "no outstanding intent"
        return views[-1].document

    def accept(self, uuid=RUNTIME_UUID, seed=10):
        intent = self.outstanding()
        return self.ok("record_queue_receipt", {"receipt_document": receipt(
            "accepted", self.artifact, self.workflow_id, seed=seed,
            runtime_task_uuid=uuid,
            intent_id=intent["intent_id"],
            idempotency_key=intent["idempotency_key"],
        )})

    def projection(self):
        return observability.project_workflow(self.conn, self.workflow_id)


