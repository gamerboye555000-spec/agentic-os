def _scenario_retry() -> Ledger:
    """Attempt 1 fails retryably with a checkpoint; attempt 2 restores it
    ACROSS the attempt boundary and succeeds."""
    art = work_spec()
    led = Ledger(art, compile_report(art))
    led.ok("validate")
    led.ok("request_dispatch")
    led.accept(uuid=RUNTIME_UUID, seed=10)
    led.ok("record_queue_receipt", {"receipt_document": receipt(
        "started", art, led.workflow_id, seed=11,
        runtime_task_uuid=RUNTIME_UUID)})
    document = checkpoint(art, led.workflow_id)
    led.ok("record_checkpoint", {"checkpoint_document": document})
    led.ok("record_result", {"result_document": result_envelope(
        art, outcome="fail", retryable=True, attempt=1,
        errors=[{"code": "transient_timeout", "message": SENTINEL_MESSAGE,
                 "retryable": True}])})
    led.ok("request_dispatch", {
        "restore_checkpoint_id": document["checkpoint_id"]
    })
    led.accept(uuid=RUNTIME_UUID_2, seed=20)
    led.ok("record_restore", {"restore_document": restore_fact(
        art, led.workflow_id, checkpoint_sha256=_digest(document))})
    led.ok("record_queue_receipt", {"receipt_document": receipt(
        "started", art, led.workflow_id, seed=21,
        runtime_task_uuid=RUNTIME_UUID_2)})
    led.ok("record_result", {"result_document": result_envelope(
        art, outcome="success", attempt=2)})
    led.checkpoint_document = document
    return led


