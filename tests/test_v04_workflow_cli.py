def _leaf_parsers():
    """The live parser's `workflow` leaves, as {verb: parser}."""
    parser = cli.build_parser()
    import argparse

    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            group = action.choices.get("workflow")
            if group is None:
                return {}
            for sub in group._actions:
                if isinstance(sub, argparse._SubParsersAction):
                    return dict(sub.choices)
    return {}


def _workflow_group():
    """The live `workflow` group parser."""
    import argparse

    parser = cli.build_parser()
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action.choices.get("workflow"), action
    return None, None


