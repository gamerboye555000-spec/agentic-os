# The frozen `cli.py` region: every module-level def whose name carries
# "workflow". No pre-existing cli.py function does.

def _region_nodes():
    tree = ast.parse(CLI_SOURCE.read_text(encoding="utf-8"))
    return [
        node for node in tree.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        and "workflow" in node.name.lower()
    ]


def _region_source() -> str:
    text = CLI_SOURCE.read_text(encoding="utf-8")
    return "\n".join(ast.get_source_segment(text, n) or "" for n in _region_nodes())


