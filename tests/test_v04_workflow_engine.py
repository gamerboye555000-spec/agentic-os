class EngineCase(unittest.TestCase):
    maxDiff = None

    def assertRefuses(self, reason, callable_, *args, **kwargs):
        with self.assertRaises(workflow_engine.WorkflowRefusal) as caught:
            callable_(*args, **kwargs)
        self.assertEqual(caught.exception.reason, reason)
        return caught.exception

    def assertRefusal(self, reason, journey, name, **kwargs):
        return self.assertRefuses(reason, journey.attempt, name, **kwargs)

    def assertEventNames(self, decision, names):
        self.assertEqual(tuple(e["event"] for e in decision.events), names)


