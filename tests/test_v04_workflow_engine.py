# Journey harness: drives real decisions, never hand-builds a reachable state.

class Journey:
    """Sequential `decide` driver. `snapshot` is always the last accepted
    snapshot; `command_id`s stay distinct so events carry honest identities."""

    def __init__(self, artifact=None, report=None, admission=None):
        self.artifact = artifact if artifact is not None else work_spec()
        self.report = (
            report if report is not None else compile_report(self.artifact)
        )
        self.counter = 0
        self.snapshot = None
        self.decisions = []
        self.events = []
        self.intents = []
        decision = self.run(
            "admit_work_spec",
            workflow_id=None,
            expected_revision=0,
            payload={
                "work_spec_document": self.artifact,
                "report_document": self.report,
            },
            facts=admission if admission is not None else facts(),
        )
        self.admission = decision

    @property
    def digest(self) -> str:
        return _digest_of(self.artifact)

    def next_command(self, name: str, **kwargs) -> dict:
        self.counter += 1
        kwargs.setdefault("command_id", self.counter)
        kwargs.setdefault(
            "expected_revision",
            0 if self.snapshot is None else self.snapshot["revision"],
        )
        if name == "admit_work_spec":
            kwargs.setdefault("workflow_id", None)
        elif self.snapshot is not None:
            kwargs.setdefault("workflow_id", self.snapshot["workflow_id"])
        return command(name, **kwargs)

    def run(self, name: str, *, facts=None, **kwargs):
        cmd = self.next_command(name, **kwargs)
        decision = workflow_engine.decide(
            self.snapshot,
            cmd,
            facts if facts is not None else workflow_engine.AdmissionFacts(),
        )
        self.snapshot = decision.snapshot_after
        self.decisions.append(decision)
        self.events.extend(decision.events)
        if decision.intent is not None:
            self.intents.append(decision.intent)
        return decision

    def attempt(self, name: str, *, facts=None, **kwargs):
        """Decide without committing the result to the journey."""
        cmd = self.next_command(name, **kwargs)
        return workflow_engine.decide(
            self.snapshot,
            cmd,
            facts if facts is not None else workflow_engine.AdmissionFacts(),
        )

    # -- shorthand drivers ------------------------------------------------
    def validate(self):
        return self.run("validate")

    def dispatch(self, **payload):
        return self.run("request_dispatch", payload=payload)

    def receipt(self, kind, **kwargs):
        kwargs.setdefault("artifact", self.artifact)
        kwargs.setdefault("workflow_id", self.snapshot["workflow_id"])
        return self.run(
            "record_queue_receipt",
            payload={"receipt_document": receipt(kind, **kwargs)},
        )

    def accept_dispatch(self, intent_seq=1, **kwargs):
        return self.receipt(
            "accepted",
            receipt_id=910 + intent_seq,
            intent_id=_intent_id(self.digest, intent_seq),
            idempotency_key=_idempotency_key(self.digest, intent_seq),
            **kwargs,
        )

    def to_state(self, state: str):
        """Drive the journey to `state` through legal edges only."""
        if state == "compiled":
            return self.snapshot
        if state == "cancelled":
            self.run("request_cancel")
            return self.snapshot
        self.validate()
        if state == "validated":
            return self.snapshot
        self.dispatch()
        self.accept_dispatch()
        if state == "scheduled":
            return self.snapshot
        self.receipt("started", receipt_id=920)
        if state == "running":
            return self.snapshot
        if state in ("waiting_input", "waiting_approval", "paused"):
            self.receipt(state, receipt_id=930)
            return self.snapshot
        if state == "succeeded":
            self.run(
                "record_result",
                payload={"result_document": result_envelope(self.artifact)},
            )
            return self.snapshot
        if state == "failed":
            self.run(
                "record_result",
                payload={
                    "result_document": result_envelope(
                        self.artifact, outcome="fail", retryable=True
                    )
                },
            )
            return self.snapshot
        raise AssertionError(f"unreachable state {state!r}")


