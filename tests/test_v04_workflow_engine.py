    def test_the_seal_guard_catches_growth_the_reserve_did_not(self):
        """`_seal_snapshot` is the backstop behind the admission reserve.

        A snapshot the store could never produce — one already at the
        canonical ceiling — must still refuse closed when the widest single
        command (a pending pointer plus `queue_route` at its maximum) would
        push the SEALED record past the bound.
        """
        route = "a" + "b" * 63
        artifact = work_spec()
        journey = Journey(artifact)
        journey.validate()
        base = journey.snapshot
        # Pad with strings inside MAX_STRING_CHARS so the ceiling is the
        # RECORD bound, not the string bound, and tune the last one by a byte
        # at a time until the widest single command would cross it.
        chunk = protocols.MAX_STRING_CHARS
        room = protocols.MAX_ARTIFACT_BYTES - len(_canon(base))
        whole = max(0, room // (chunk + 3))

        def ceiling(tune):
            padding = ["z" * chunk for _ in range(whole)] + ["y" * tune]
            body = _seal({**journey.report, "defaults_applied": padding})
            return synthetic(
                base, report_document=body, report_sha256=_digest_of(body)
            )

        # The tune string costs exactly one byte per character, so the length
        # that fills the record is arithmetic, not a search.
        headroom = protocols.MAX_ARTIFACT_BYTES - len(_canon(ceiling(0)))
        self.assertGreater(headroom, 240)
        self.assertLessEqual(headroom, protocols.MAX_STRING_CHARS)
        fired = 0
        verified = 0
        for delta in range(0, 240):
            at_ceiling = ceiling(headroom - delta)
            if len(_canon(at_ceiling)) > protocols.MAX_ARTIFACT_BYTES:
                continue
            try:
                workflow_engine._verify_snapshot(at_ceiling)
            except workflow_engine.WorkflowRefusal:
                continue     # not a legal input; nothing to prove here
            verified += 1
            journey.snapshot = at_ceiling
            try:
                decision = journey.attempt(
                    "request_dispatch", payload={"queue_route": route}
                )
            except workflow_engine.WorkflowRefusal as refusal:
                self.assertEqual(refusal.reason, "snapshot_divergence")
                fired += 1
                continue
            self.assertLessEqual(
                len(_canon(decision.snapshot_after)),
                protocols.MAX_ARTIFACT_BYTES,
                "decide returned a snapshot outside the canonical record",
            )
        self.assertGreater(verified, 0, "no legal ceiling snapshot was built")
        self.assertGreater(
            fired, 0, "the seal guard was never exercised by this sweep"
        )

    def test_fold_bounds_its_intent_collections(self):
        """A history `verify_history` certifies must fold, not crash: fold's
        accumulators are the same §9 bounded collections."""
        journey = Journey()
        journey.validate()
        journey.dispatch()
        journey.run("revoke_dispatch")
        request = next(
            e for e in journey.events if e["event"] == "dispatch_requested"
        )
        revoke = next(
            e for e in journey.events if e["event"] == "dispatch_revoked"
        )
        events = [dict(e) for e in journey.events]
        seq = events[-1]["seq"]
        revision = events[-1]["revision"]
        for index in range(protocols.MAX_ARRAY_ITEMS + 8):
            revision += 1
            command_id = _uuid_n(6000 + index)
            seq += 1
            events.append(_seal({
                **request, "seq": seq, "revision": revision,
                "command_id": command_id,
                "payload": {
                    "intent_id": _intent_id(journey.digest, 100 + index),
                    "queue_route": "default",
                },
            }))
            seq += 1
            events.append(_seal({
                **revoke, "seq": seq, "revision": revision,
                "command_id": command_id,
                "payload": {
                    "intent_id": _intent_id(journey.digest, 100 + index),
                    "cancel_intent_id": _intent_id(journey.digest, 900 + index),
                },
            }))
        self.assertIsNone(workflow_engine.verify_history(events))
        refusal = self.assertRefuses(
            "snapshot_divergence", workflow_engine.fold, events
        )
        # Named by the accumulator, not by the seal: fold bounds the
        # collection as it builds it, so the refusal points at the field.
        self.assertEqual(refusal.where, "/revoked_intent_ids")


