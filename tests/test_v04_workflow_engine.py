class FoldSafetyTests(EngineCase):
    """F04: a history verify_history certifies must never crash fold."""

    def _rich_journey(self) -> Journey:
        journey = Journey()
        journey.validate()
        journey.dispatch()
        journey.run("revoke_dispatch")
        journey.dispatch()
        journey.accept_dispatch(intent_seq=3)
        journey.receipt("started", receipt_id=940)
        journey.receipt("waiting_approval", receipt_id=941)
        journey.run(
            "record_approval",
            payload={
                "approval_document": approval_fact(
                    artifact=journey.artifact,
                    scope="runtime",
                    approval_ref="runtime.approvals/v1",
                )
            },
        )
        journey.receipt("resumed", receipt_id=942)
        journey.run("request_cancel")
        return journey

    def test_blanking_any_load_bearing_payload_is_refused(self):
        journey = self._rich_journey()
        checked = 0
        for index, event in enumerate(journey.events):
            if not event["payload"]:
                continue
            broken = [dict(e) for e in journey.events]
            broken[index] = _seal({**broken[index], "payload": {}})
            verdict = workflow_engine.verify_history(broken)
            if verdict is None:
                # Certified clean: it must then be fold-safe.
                workflow_engine.fold(broken)
            else:
                self.assertEqual(verdict.reason, "history_corrupt", index)
                self.assertRefuses(
                    "history_corrupt", workflow_engine.fold, broken
                )
                checked += 1
        self.assertGreaterEqual(checked, 5)

    def test_every_certified_history_folds(self):
        journey = self._rich_journey()
        for index, event in enumerate(journey.events):
            for mutation in ({"payload": {}}, {"payload": {"junk": 1}}):
                broken = [dict(e) for e in journey.events]
                broken[index] = _seal({**broken[index], **mutation})
                if workflow_engine.verify_history(broken) is None:
                    workflow_engine.fold(broken)

    def test_each_required_payload_key_is_individually_required(self):
        """Dropping ONE load-bearing key must refuse; blanking the whole
        payload would be caught by any single rule and proves less."""
        journey = self._rich_journey()
        checked = 0
        for index, event in enumerate(journey.events):
            for key in event["payload"]:
                trimmed = {
                    k: v for k, v in event["payload"].items() if k != key
                }
                broken = [dict(e) for e in journey.events]
                broken[index] = _seal({**broken[index], "payload": trimmed})
                verdict = workflow_engine.verify_history(broken)
                if verdict is None:
                    workflow_engine.fold(broken)
                else:
                    self.assertEqual(
                        verdict.reason, "history_corrupt", f"{index}/{key}"
                    )
                    checked += 1
        self.assertGreaterEqual(checked, 10)

    def test_payload_value_types_are_verified(self):
        journey = Journey()
        journey.validate()
        journey.dispatch()
        broken = [dict(e) for e in journey.events]
        broken[-1] = _seal({
            **broken[-1],
            "payload": {**broken[-1]["payload"], "intent_id": 7},
        })
        self.assertEqual(
            workflow_engine.verify_history(broken).reason, "history_corrupt"
        )


