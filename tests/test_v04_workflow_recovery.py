# Test-local canonical sealing. The engine's `_seal` is private and is NOT
# imported: a fixture the engine sealed could not falsify the engine.

def _executable(source: str, node) -> str:
    """A function's source WITHOUT its docstring.

    Every scan in this file that forbids a token is about code, not prose: a
    comment or docstring that names a forbidden thing in order to forbid it is
    the documentation, not the defect.
    """
    body = list(node.body)
    if (
        body
        and isinstance(body[0], ast.Expr)
        and isinstance(body[0].value, ast.Constant)
        and isinstance(body[0].value.value, str)
    ):
        body = body[1:]
    return "\n".join(ast.get_source_segment(source, n) or "" for n in body)


def _seal(body: dict) -> dict:
    record = protocols.parse_canonical(protocols.serialize_canonical(
        {k: v for k, v in body.items() if k != "content_sha256"}
    ))
    record["content_sha256"] = protocols.content_digest(record)
    return record


def _digest(document: dict) -> str:
    return protocols.content_digest(document)


def _uuid(seed: int) -> str:
    raw = hashlib.sha256(f"u-w3-fixture:{seed}".encode()).digest()[:16]
    b = bytearray(raw)
    b[6] = (b[6] & 0x0F) | 0x80
    b[8] = (b[8] & 0x3F) | 0x80
    t = b.hex()
    return f"{t[0:8]}-{t[8:12]}-{t[12:16]}-{t[16:20]}-{t[20:32]}"


