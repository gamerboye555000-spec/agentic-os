    def test_w18_a_coordinated_row_rewrite_is_reported_and_never_restorable(self):
        """§22 A29.1. Rewriting the body, its digest COLUMN and the row hash
        together defeats every check that compares a row against itself.

        The `checkpoint_recorded` event sealed the digest of the body it
        accepted, independently of the row the body sits in — so that is what
        the stored bytes are bound to. Without it, `verify` reported `ok` on a
        forged checkpoint and the forged digest flowed into the dispatch
        intent that CROSSES THE TRUST BOUNDARY.
        """
        ledger = self._running()
        document = checkpoint(ledger.artifact, ledger.workflow_id)
        ledger.ok("record_checkpoint", {"checkpoint_document": document})
        row = ledger.conn.execute(
            "SELECT * FROM workflow_checkpoints"
        ).fetchone()
        forged = checkpoint(
            ledger.artifact, ledger.workflow_id,
            payload={"cursor": 99999, "evil": True},
        )
        rewritten = list(row)
        rewritten[6] = protocols.serialize_canonical(forged).decode("utf-8")
        rewritten[7] = _digest(forged)
        rewritten[8] = len(protocols.serialize_canonical(forged["payload"]))
        row_hash = workflow_store._row_digest(
            workflow_store._checkpoint_row_payload(tuple(rewritten))
        )
        with ledger.conn:
            ledger.conn.execute(
                "UPDATE workflow_checkpoints SET document = ?, "
                "document_sha256 = ?, payload_bytes = ?, content_sha256 = ? "
                "WHERE id = ?",
                (rewritten[6], rewritten[7], rewritten[8], row_hash, row[0]),
            )
        # Every self-consistent check passes; the EVENT does not.
        reports = workflow_store.verify(ledger.conn, ledger.workflow_id)
        self.assertEqual(reports[0].integrity, "snapshot_divergence")
        self.assertIn(
            ("workflow_checkpoints", row[0]), reports[0].divergent_rows
        )
        # And the forged row can never become the restore authority.
        ledger.ok("record_result", {"result_document": result_envelope(
            ledger.artifact, outcome="fail", retryable=True, attempt=1,
            result_id=_uuid(901),
        )})
        out = ledger.refused("request_dispatch", {
            "restore_checkpoint_id": document["checkpoint_id"]
        })
        self.assertEqual(out.reason, "checkpoint_ineligible")

