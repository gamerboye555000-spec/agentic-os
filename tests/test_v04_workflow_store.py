# S18 - SQL, message and text safety (§18.5, §18.6)

_TABLE_CONSTANTS = frozenset((
    "WORKFLOWS_TABLE", "WORKFLOW_EVENTS_TABLE", "WORKFLOW_COMMANDS_TABLE",
    "WORKFLOW_INTENTS_TABLE", "WORKFLOW_RECEIPTS_TABLE",
    "WORKFLOW_FACTS_TABLE", "WORKFLOW_ATTEMPTS_TABLE",
    "WORKFLOW_CHECKPOINTS_TABLE",
))

_FORBIDDEN_SQL = (
    "DELETE", "DROP", "ALTER", "ATTACH", "PRAGMA", "executescript",
)
_FORBIDDEN_NAMES = (
    "eval", "exec", "compile", "__import__", "importlib", "subprocess",
    "os.system", "socket",
)


def _sql_constants(tree):
    """Module-level string constants and how they were built."""
    out = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name):
            continue
        out[target.id] = node.value
    return out


def _referenced_db_attrs(node) -> set:
    return {
        child.attr
        for child in ast.walk(node)
        if isinstance(child, ast.Attribute)
        and isinstance(child.value, ast.Name)
        and child.value.id == "db"
    }


class SqlAndTextSafetyTests(StoreCase):
    def test_every_sql_argument_is_a_literal_or_a_table_constant(self):
        """Every statement reaching SQLite is a string literal or a
        module-level constant built only from `db.*_TABLE` names.

        The module funnels its statements through `_execute`/`_fetchone`/
        `_fetchall`, so the check covers both the direct `conn.execute` calls
        and every call site of those three helpers — the one place a caller
        value could otherwise be concatenated into SQL.
        """
        tree = _store_ast()
        constants = _sql_constants(tree)
        checked = 0
        finalize_sites = 0

        def check(argument, where):
            nonlocal checked
            checked += 1
            if isinstance(argument, ast.Constant):
                self.assertIsInstance(argument.value, str, where)
                return
            self.assertIsInstance(argument, ast.Name, f"{where}: {ast.dump(argument)}")
            self.assertIn(argument.id, constants, f"{where}: {argument.id}")
            attrs = _referenced_db_attrs(constants[argument.id])
            self.assertTrue(
                attrs <= _TABLE_CONSTANTS,
                f"{argument.id} interpolates {sorted(attrs - _TABLE_CONSTANTS)}",
            )

        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            if (isinstance(node.func, ast.Attribute)
                    and node.func.attr == "execute"):
                # The one indirection: `_execute(conn, sql, params)` forwards
                # its own parameter, and every CALL SITE of it is checked below.
                if isinstance(node.args[0], ast.Name) and node.args[0].id == "sql":
                    continue
                check(node.args[0], "conn.execute")
            elif (isinstance(node.func, ast.Name)
                  and node.func.id in ("_execute", "_fetchone", "_fetchall")):
                # Two forwarding parameters exist: `_fetchone`/`_fetchall` pass
                # their own `sql` to `_execute`, and `_finalize` passes its own
                # `row_sql`/`sql`. Skipping a forwarded PARAMETER would be a
                # hole if the forwarder's own call sites went unchecked, so
                # they are checked below and asserted non-empty.
                if (isinstance(node.args[1], ast.Name)
                        and node.args[1].id in ("sql", "row_sql")):
                    continue
                check(node.args[1], node.func.id)
            elif (isinstance(node.func, ast.Name)
                  and node.func.id == "_finalize"):
                check(node.args[1], "_finalize/sql")
                check(node.args[2], "_finalize/row_sql")
                finalize_sites += 1
        self.assertGreater(checked, 20)
        # Every §5.8 hash finalization must be one of the checked call sites,
        # so the `row_sql` exemption above can never hide one.
        # Six row-hash finalizations now: the four landed ones plus the
        # attempt INSERT's and the checkpoint INSERT's (U-W3 §11.3).
        self.assertEqual(finalize_sites, 6)

