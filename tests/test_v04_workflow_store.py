# S9 - envelope subset agreement (§10.2)

class EnvelopeSubsetTests(StoreCase):
    def _subset_accepts(self, document):
        try:
            self.store._command_identity(document)
            return True
        except Exception:  # noqa: BLE001 - the private sentinel is internal
            return False

    def _decide_accepts_on_the_four_fields(self, document):
        """Does `decide` reject on `command_id`, `workflow_id`, verb membership
        or the self-digest? Any OTHER refusal is not the subset's business."""
        subset_codes = {"command_malformed", "command_unknown"}
        subset_paths = {
            "/", "/command", "/command_id", "/workflow_id",
            f"/{protocols.CONTENT_HASH_FIELD}",
        }
        try:
            workflow_engine.decide(
                None, document, workflow_engine.ShellFacts()
            )
        except workflow_engine.WorkflowRefusal as refusal:
            if refusal.reason in subset_codes and refusal.where in subset_paths:
                return False
            return True
        return True

    def test_subset_and_decide_agree_over_a_malformed_corpus(self):
        good = command("validate", workflow_id="WF-7", expected_revision=1)
        corpus = [
            good,
            dict(good, command_id="not-a-uuid"),
            dict(good, command_id=7),
            dict(good, command="nonsuch"),
            dict(good, command=7),
            dict(good, workflow_id="WF-"),
            dict(good, workflow_id="X-7"),
            dict(good, workflow_id=7),
            dict(good, content_sha256="0" * 64),
            _seal(dict(good, actor="agent:x")),
            command("admit_work_spec", workflow_id=None, expected_revision=0,
                    payload={"work_spec_document": {}, "report_document": {}}),
            _seal(dict(
                command("admit_work_spec", workflow_id=None,
                        expected_revision=0),
                workflow_id="WF-7",
            )),
            "not a dict",
            {"schema": "aos.workflow-command/v1"},
        ]
        for index, document in enumerate(corpus):
            with self.subTest(index=index):
                self.assertEqual(
                    self._subset_accepts(document),
                    self._decide_accepts_on_the_four_fields(document),
                    document,
                )

    def test_the_subset_recomputes_the_digest_rather_than_trusting_it(self):
        good = command("validate", workflow_id="WF-7", expected_revision=1)
        lying = dict(good, content_sha256="f" * 64)
        self.assertFalse(self._subset_accepts(lying))
        fresh, _verb, _cid, _wid, digest = self.store._command_identity(good)
        self.assertEqual(digest, _digest_of(good))
        self.assertEqual(fresh[protocols.CONTENT_HASH_FIELD], digest)


