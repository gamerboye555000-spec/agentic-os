class _Boom(RuntimeError):
    """The forced exception every crash point injects."""


class CrashMatrixTests(StoreCase):
    """Every K0-K14 and KA0-KA8 point of §13, by the three frozen mechanisms:
    (i) the nine mutation helpers, (ii) the transaction entry / dedupe read /
    `_load_snapshot` / `decide` / task-read boundaries, and (iii) the
    mid-`_insert_events` wrapper for K6."""

    def _state(self, row_id):
        return (self.counts(row_id), self.workflow_row(row_id))

    def _assert_crash(self, journey, document, patch_factory, label):
        from unittest import mock

        row_id = journey.row_id if journey is not None else None
        before = self._state(row_id)
        target, replacement = patch_factory()
        with self.assertRaises(Exception, msg=label):
            with mock.patch.object(*target, replacement):
                self.store.submit(self.conn, document)
        self.assertEqual(self._state(row_id), before, f"{label}: state moved")
        # ... and the retried command then succeeds.
        outcome = self.store.submit(self.conn, document)
        self.assertEqual(outcome.status, "accepted", f"{label}: {outcome.reason}")
        return outcome

    def _helper(self, name):
        def factory():
            def boom(*_a, **_k):
                raise _Boom(name)
            return (self.store, name), boom
        return factory

    def _after_helper(self, name):
        real = getattr(self.store, name)

        def factory():
            def wrapper(*a, **k):
                real(*a, **k)
                raise _Boom(f"after {name}")
            return (self.store, name), wrapper
        return factory

