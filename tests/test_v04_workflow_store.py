class SnapshotRebuildTests(StoreCase):
    def test_load_snapshot_reproduces_every_decision_snapshot(self):
        journey = Journey(self)
        journey.validate()
        journey.dispatch()
        journey.accept_dispatch()
        journey.receipt("started", receipt_id=920)
        journey.receipt("waiting_input", receipt_id=930)
        journey.receipt("resumed", receipt_id=940)
        for outcome in journey.outcomes:
            self.assertEqual(outcome.status, "accepted", outcome.reason)
        # Every accepted outcome's snapshot must be exactly what a fresh
        # rebuild from the stored rows produces — byte-identical canonical
        # bytes, including content_sha256.
        rebuilt = self.store.rebuild(self.conn, journey.workflow_id)
        self.assertEqual(rebuilt.integrity, "ok")
        last = journey.outcomes[-1].snapshot
        self.assertEqual(_canon(rebuilt.snapshot), _canon(last))
        self.assertEqual(
            rebuilt.snapshot["content_sha256"], last["content_sha256"]
        )

    def test_local_sealer_matches_the_engine_seal(self):
        journey = Journey(self)
        snapshot = journey.admission.snapshot
        body = {k: v for k, v in snapshot.items() if k != "content_sha256"}
        self.assertEqual(self.store._seal(body), snapshot)
        self.assertEqual(
            self.store._seal(snapshot)["content_sha256"],
            _digest_of(snapshot),
        )

    def test_stored_content_sha256_is_the_snapshot_record_digest(self):
        journey = Journey(self)
        row = self.workflow_row(journey.row_id)
        self.assertEqual(row[19], journey.admission.snapshot["content_sha256"])
        self.assertEqual(row[19], _digest_of(journey.admission.snapshot))

    def test_timestamps_are_outside_the_agreement_gate(self):
        journey = Journey(self)
        journey.validate()
        # Moving a timestamp alone must not make the workflow diverge: the two
        # row timestamps have no snapshot counterpart (§7.2 step 6).
        with self.conn:
            self.conn.execute(
                "UPDATE workflows SET updated_at = ? WHERE id = ?",
                ("2099-01-01T00:00:00Z", journey.row_id),
            )
        self.assertEqual(
            self.store.read_workflow(self.conn, journey.workflow_id).integrity,
            "ok",
        )
        outcome = journey.dispatch()
        self.assertEqual(outcome.status, "accepted", outcome.reason)

    def test_a_tampered_projection_column_diverges_and_refuses(self):
        journey = Journey(self)
        journey.validate()
        with self.conn:
            self.conn.execute(
                "UPDATE workflows SET state = 'paused' WHERE id = ?",
                (journey.row_id,),
            )
        record = self.store.read_workflow(self.conn, journey.workflow_id)
        self.assertEqual(record.integrity, "snapshot_divergence")
        outcome = journey.dispatch()
        self.assertEqual(outcome.status, "refused")
        self.assertEqual(outcome.reason, "snapshot_divergence")
        self.assertEqual(outcome.events, ())


