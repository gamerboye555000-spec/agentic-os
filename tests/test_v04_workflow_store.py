class Journey:
    """Sequential `submit` driver. `command_id`s stay distinct so events carry
    honest identities; `expected_revision` always tracks the last accepted
    outcome, so no test hand-builds a reachable revision."""

    #: Distinct `command_id` namespaces per journey. `command_id` is UNIQUE
    #: across the whole table, so two journeys sharing a database would
    #: otherwise collide on their first command and the second would be
    #: refused `command_conflict` rather than admitted.
    _next_base = 1000

    def __init__(self, case: StoreCase, artifact=None, report=None,
                 admit=True):
        self.case = case
        self.conn = case.conn
        self.store = case.store
        self.artifact = artifact if artifact is not None else work_spec()
        self.report = (
            report if report is not None else compile_report(self.artifact)
        )
        Journey._next_base += 1000
        self.base = Journey._next_base
        self.counter = 0
        self.revision = 0
        self.outcomes = []
        self.admission = None
        if admit:
            self.admission = self.run(
                "admit_work_spec",
                payload={
                    "work_spec_document": self.artifact,
                    "report_document": self.report,
                },
            )

    @property
    def digest(self) -> str:
        return _digest_of(self.artifact)

    @property
    def workflow_id(self) -> str:
        return _workflow_identity(self.digest)

    @property
    def row_id(self) -> int:
        return int(self.workflow_id.split("-")[1])

    def next_command(self, name, **kwargs) -> dict:
        self.counter += 1
        kwargs.setdefault("command_id", self.base + self.counter)
        kwargs.setdefault("expected_revision", self.revision)
        if name != "admit_work_spec":
            kwargs.setdefault("workflow_id", self.workflow_id)
        return command(name, **kwargs)

    def run(self, name, **kwargs):
        outcome = self.store.submit(self.conn, self.next_command(name, **kwargs))
        self.outcomes.append(outcome)
        if outcome.status == "accepted":
            self.revision = outcome.revision
        return outcome

    def attempt(self, name, **kwargs):
        """Submit without adopting the result into the journey's revision."""
        return self.store.submit(self.conn, self.next_command(name, **kwargs))

    # -- shorthand drivers -------------------------------------------------
    def validate(self):
        return self.run("validate")

    def dispatch(self, **payload):
        return self.run("request_dispatch", payload=payload)

    def receipt(self, kind, **kwargs):
        kwargs.setdefault("artifact", self.artifact)
        kwargs.setdefault("workflow_id", self.workflow_id)
        # `receipt_id` is UNIQUE across the whole table, so it needs the same
        # per-journey namespace `command_id` gets.
        if isinstance(kwargs.get("receipt_id"), int):
            kwargs["receipt_id"] = self.base + kwargs["receipt_id"]
        return self.run(
            "record_queue_receipt",
            payload={"receipt_document": receipt(kind, **kwargs)},
        )

    def accept_dispatch(self, intent_seq=1, **kwargs):
        return self.receipt(
            "accepted",
            receipt_id=910 + intent_seq,  # namespaced by `receipt` above
            intent_id=_intent_id(self.digest, intent_seq),
            idempotency_key=_idempotency_key(self.digest, intent_seq),
            **kwargs,
        )

    def to_state(self, state: str):
        if state == "compiled":
            return
        if state == "cancelled":
            self.run("request_cancel")
            return
        self.validate()
        if state == "validated":
            return
        self.dispatch()
        self.accept_dispatch()
        if state == "scheduled":
            return
        self.receipt("started", receipt_id=920)
        if state == "running":
            return
        if state in ("waiting_input", "waiting_approval", "paused"):
            self.receipt(state, receipt_id=930)
            return
        if state == "succeeded":
            self.run(
                "record_result",
                payload={"result_document": result_envelope(self.artifact)},
            )
            return
        if state == "failed":
            self.run(
                "record_result",
                payload={
                    "result_document": result_envelope(
                        self.artifact, outcome="fail", retryable=True
                    )
                },
            )
            return
        raise AssertionError(f"unreachable state {state!r}")


