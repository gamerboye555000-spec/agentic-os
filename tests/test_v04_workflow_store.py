class _V6TestCase(unittest.TestCase):
    """An in-memory v6 database carrying the one `tasks` parent row the
    `workflows` foreign key needs. No hash here is real: these rows exercise
    storage constraints, not integrity verification."""

    maxDiff = None

    def setUp(self):
        self.conn = db.connect(":memory:")
        self.addCleanup(self.conn.close)
        self.conn.executescript(db.SCHEMA_SQL)
        _insert(
            self.conn,
            "tasks",
            dict(
                id=1,
                project_id=None,
                title="t",
                kind="code",
                status="ready",
                priority=2,
                created_at=NOW,
                updated_at=NOW,
            ),
        )
        self.conn.commit()

    def query(self, sql, params=()):
        return self.conn.execute(sql, params).fetchall()

    def assertRejects(self, table: str, row: dict, msg: str = ""):
        # Roll back explicitly rather than through `with conn:` — the context
        # manager would also discard the committed parent rows this case
        # depends on if an earlier statement in the same implicit transaction
        # were still open.
        try:
            with self.assertRaises(sqlite3.IntegrityError, msg=msg or repr(row)):
                _insert(self.conn, table, row)
        finally:
            self.conn.rollback()

    def assertAccepts(self, table: str, row: dict):
        _insert(self.conn, table, row)
        self.conn.commit()


