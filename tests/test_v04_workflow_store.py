# S17 - hostile rows and raw exception closure (§18.4)

_CLOSED_EXCEPTIONS = (
    sqlite3.Error, protocols.ProtocolError, KeyError, TypeError, ValueError,
    AttributeError,
)


class HostileRowTests(StoreCase):
    """Over a matrix that tampers every column of all six tables, no public
    function may raise `sqlite3.Error`, `ProtocolError`, `KeyError`,
    `TypeError`, `ValueError` or `AttributeError`. Every call must return a
    `StoreOutcome`, a view with an integrity verdict, or a `WorkflowStoreError`
    carrying one of the three closed codes."""

    #: Values a hostile writer, a corrupted file, or a tampered backup can put
    #: in a column: wrong type, NULL, oversized, non-canonical, BOM-prefixed,
    #: duplicate-keyed, INT_MAX overflow, and a 257-element array.
    HOSTILE_VALUES = (
        7,
        None,
        "x" * 9000,
        "{not canonical",
        "﻿{}",
        '{"a":1,"a":2}',
        str(protocols.INT_MAX + 1),
        "[" + ",".join("1" for _ in range(257)) + "]",
        b"\x00\x01",
        "",
    )

    #: The seven child tables in FK-CHILD-FIRST order. `workflow_checkpoints`
    #: references `workflow_attempts(workflow_id, attempt_no)`,
    #: `workflow_attempts` references `workflow_intents(intent_id)`, and the
    #: connection runs with `foreign_keys=ON`, so `_restore` deletes in this
    #: order and re-inserts in the reverse of it. No hostile column is a
    #: `workflow_id`, so `WHERE workflow_id = ?` still selects exactly the
    #: tampered journey's rows after every tamper in the matrix.
    _CHILD_TABLES = (
        "workflow_checkpoints", "workflow_attempts", "workflow_receipts",
        "workflow_facts", "workflow_commands", "workflow_events",
        "workflow_intents",
    )

    #: Set the moment one hostile value's clean baseline cannot be put back
    #: exactly. `subTest` swallows what `_restore` raises so the loop can
    #: carry on; the matrix reads this instead and stops, because a lost
    #: baseline is the one failure no later value can be read through.
    _restoration_failure = None

    def _exercise(self, journey, label):
        calls = (
            ("submit", lambda: self.store.submit(
                self.conn,
                command("validate", workflow_id=journey.workflow_id,
                        expected_revision=1, command_id=journey.base + 700))),
            ("read_workflow", lambda: self.store.read_workflow(
                self.conn, journey.workflow_id)),
            ("list_workflows", lambda: self.store.list_workflows(self.conn)),
            ("read_history", lambda: self.store.read_history(
                self.conn, journey.workflow_id)),
            ("list_outstanding_intents",
             lambda: self.store.list_outstanding_intents(self.conn)),
            ("rebuild", lambda: self.store.rebuild(
                self.conn, journey.workflow_id)),
            ("verify", lambda: self.store.verify(self.conn)),
        )
        for name, call in calls:
            try:
                result = call()
            except self.store.WorkflowStoreError as error:
                self.assertIn(error.code, self.store.STORE_ERROR_CODES)
                continue
            except _CLOSED_EXCEPTIONS as escaped:  # pragma: no cover
                self.fail(
                    f"{label}/{name}: {type(escaped).__name__} escaped the "
                    f"public boundary"
                )
            if name == "submit":
                self.assertIn(result.status, self.store.STORE_STATUSES)
            elif name in ("read_workflow",):
                if result is not None:
                    self.assertIn(result.integrity, self.store.STORE_INTEGRITY)
            elif name in ("read_history", "rebuild"):
                self.assertIn(result.integrity, self.store.STORE_INTEGRITY)
            elif name == "verify":
                for report in result:
                    self.assertIn(
                        report.integrity, self.store.STORE_INTEGRITY
                    )

